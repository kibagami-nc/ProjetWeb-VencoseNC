-- =========================================================
-- 1. ROLES (indépendante)
-- =========================================================
CREATE TABLE roles (
    id_role BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role    VARCHAR(50) NOT NULL
);

-- =========================================================
-- 2. USERS (indépendante)
-- =========================================================
CREATE TABLE users (
    id_user           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name         VARCHAR(50)  NOT NULL,
    first_name        VARCHAR(50)  NOT NULL,
    email             VARCHAR(100) NOT NULL UNIQUE,
    phone_mobile      VARCHAR(20),
    phone_landline    VARCHAR(20),
    password          VARCHAR(255) NOT NULL,
    registration_date TIMESTAMP,
    is_active         BOOLEAN
);

-- =========================================================
-- 3. BIDS (dépend de users)
-- =========================================================
CREATE TABLE bids (
    id_bid        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(100)  NOT NULL,
    description   VARCHAR(1000) NOT NULL,
    price         INTEGER,
    location      VARCHAR(30),
    creation_date TIMESTAMP,
    fk_id_user    BIGINT NOT NULL,
    CONSTRAINT fk_bids_user FOREIGN KEY (fk_id_user) REFERENCES users (id_user)
);

-- =========================================================
-- 4. PHOTOS (dépend de bids)
-- =========================================================
CREATE TABLE photos (
    id_photo  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_url VARCHAR(255) NOT NULL,
    fk_id_bid BIGINT NOT NULL,
    CONSTRAINT fk_photos_bid FOREIGN KEY (fk_id_bid) REFERENCES bids (id_bid)
);

-- =========================================================
-- 5. THREADS (dépend de bids)
-- =========================================================
CREATE TABLE threads (
    id_thread BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title     VARCHAR(100) NOT NULL,
    fk_id_bid BIGINT NOT NULL,
    CONSTRAINT fk_threads_bid FOREIGN KEY (fk_id_bid) REFERENCES bids (id_bid)
);

-- =========================================================
-- 6. MESSAGES (dépend de threads et users)
-- =========================================================
CREATE TABLE messages (
    id_message   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content      VARCHAR(1000) NOT NULL,
    sent_at      TIMESTAMP,
    fk_id_thread BIGINT NOT NULL,
    fk_id_user   BIGINT NOT NULL,
    CONSTRAINT fk_messages_thread FOREIGN KEY (fk_id_thread) REFERENCES threads (id_thread),
    CONSTRAINT fk_messages_user   FOREIGN KEY (fk_id_user)   REFERENCES users (id_user)
);

-- =========================================================
-- 7. USERS_ROLES (jointure ManyToMany users <-> roles)
-- =========================================================
CREATE TABLE users_roles (
    fk_id_user BIGINT NOT NULL,
    fk_id_role BIGINT NOT NULL,
    PRIMARY KEY (fk_id_user, fk_id_role),
    CONSTRAINT fk_ur_user FOREIGN KEY (fk_id_user) REFERENCES users (id_user),
    CONSTRAINT fk_ur_role FOREIGN KEY (fk_id_role) REFERENCES roles (id_role)
);

-- =========================================================
-- 8. USERS_THREADS (jointure ManyToMany users <-> threads)
-- =========================================================
CREATE TABLE users_threads (
    fk_id_user   BIGINT NOT NULL,
    fk_id_thread BIGINT NOT NULL,
    PRIMARY KEY (fk_id_user, fk_id_thread),
    CONSTRAINT fk_ut_user   FOREIGN KEY (fk_id_user)   REFERENCES users (id_user),
    CONSTRAINT fk_ut_thread FOREIGN KEY (fk_id_thread) REFERENCES threads (id_thread)
);

